let test_prompt_1_concrete () =
  Printf.printf "  [TEST 1] Testing concrete unseen request 1 (system_status.log)...\n";
  let prompt = "Instruction: Write system status log to system_status.log stating that microkernel memory paging and capability gates are active" in
  let req = {
    Inos_models.Protocol.request_id = "req-g12-test-01";
    model_name = "llama2-stories15M-pretrained";
    prompt;
    max_tokens = 40;
    temperature = 0.0;
    timeout_seconds = 10.0;
  } in
  match PretrainedLlamaAdapter.invoke_buffered req with
  | Error _ -> failwith "Model generation failed for prompt 1"
  | Ok resp ->
      Printf.printf "         Generated %d tokens: '%s'\n" resp.total_tokens (String.sub resp.full_text 0 (min 60 (String.length resp.full_text)));
      match compile_live_intent ~prompt ~generated_tokens:resp.full_text with
      | AmbiguousInstructionHalted _ -> failwith "Prompt 1 should have compiled to concrete operation"
      | ConcreteOperation op ->
          assert (op.target_filename = "system_status.log");
          assert (op.is_ambiguous = false);
          assert (String.length op.provenance.content_hash = 64 || String.length op.provenance.content_hash = 32);
          assert (Result.is_ok (validate_and_order_dag op.operation_graph));
          Printf.printf "  [PASS] Request 1 compiled to valid Operation IR (target: %s, provenance hash: %s)\n"
            op.target_filename op.provenance.content_hash

