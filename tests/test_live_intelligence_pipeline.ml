let test_prompt_3_ambiguous () =
  Printf.printf "  [TEST 3] Testing deliberately ambiguous request (no concrete target/directive)...\n";
  let prompt = "Instruction: Update things and do whatever is necessary with the stuff" in
  let generated = "Instruction: Update things and do whatever is necessary with the stuff.\nOnce upon a time..." in
  match compile_live_intent ~prompt ~generated_tokens:generated with
  | ConcreteOperation _ -> failwith "Ambiguous instruction must NOT produce concrete operation"
  | AmbiguousInstructionHalted h ->
      assert (h.is_ambiguous = true);
      Printf.printf "  [PASS] Ambiguous instruction halted safely without operation emission: '%s'\n" h.reason

let test_spool_serialization () =
  Printf.printf "  [TEST 4] Testing dedicated transport spool sector serialization...\n";
  let filename = "system_status.log" in
  let payload = "Exact live model generated bytes: kernel memory verified active." in
  let prov_hash = "abc123def456" in
  let prompt_hash = "prompt789" in
  let sectors = serialize_spool_sectors ~filename ~payload ~provenance_hash:prov_hash ~prompt_hash ~is_ambiguous:false in
  assert (List.length sectors = 2); (* 1 header + 1 payload block *)
  let hdr = List.hd sectors in
  assert (Bytes.length hdr = 512);
  assert (Bytes.sub_string hdr 0 4 = "INT_");
  assert (Bytes.get hdr 4 = '\x01'); (* version 1 *)
  assert (Bytes.get hdr 112 = '\x00'); (* not ambiguous *)
  let data_blk = List.nth sectors 1 in
  assert (Bytes.length data_blk = 512);
  assert (String.starts_with ~prefix:payload (Bytes.to_string data_blk));
  Printf.printf "  [PASS] Transport spool serialized into %d sectors with valid header magic 'INT_'\n" (List.length sectors)

let test_fnwd_simd_pipeline () =
  Printf.printf "  [TEST 5] Testing executable FNWD 8-lane vectorized filter_and_transform_avx2 pipeline...\n";
  let raw_input = "INOS\tFNWD\x01\x02 vectorized stream verification payload with 8-lane unrolled dispatch\n" in
  let recp = execute_fnwd_simd_pipeline raw_input in
  assert (recp.op_name = "x86_64_simd.filter_and_transform_avx2");
  assert (recp.lanes_width = 8);
  assert (recp.filtered_control_bytes = 2);
  assert (recp.vectorized_blocks_8x >= 9);
  assert (String.length recp.output_sha256 = 64);
  Printf.printf "  [PASS] FNWD 8-lane vectorized pipeline verified (%d blocks, %d control bytes filtered, sha256=%s...)\n"
    recp.vectorized_blocks_8x recp.filtered_control_bytes (String.sub recp.output_sha256 0 16)

