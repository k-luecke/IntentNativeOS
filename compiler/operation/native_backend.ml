(* compiler/operation/native_backend.ml - Native-code backend prototype for pure functions (C007)
   Lowers a pure IR function to native code and verifies that the compiled binary
   yields identical numerical results across test vectors as the reference interpreter.
*)

type binop =
  | Add
  | Sub
  | Mul
  | Xor
  | And
  | Or
  | Shl
  | Shr

type expr =
  | Const of int64
  | Var of string
  | BinOp of binop * expr * expr
  | IfZero of expr * expr * expr

type pure_func = {
  name: string;
  params: string list;
  body: expr;
}

(* 1. Deterministic Reference Interpreter *)
let rec eval_expr (env : (string * int64) list) (e : expr) : int64 =
  match e with
  | Const n -> n
  | Var v ->
      (match List.assoc_opt v env with
       | Some n -> n
       | None -> failwith (Printf.sprintf "Unbound variable '%s' in reference interpreter" v))
  | BinOp (op, left, right) ->
      let l = eval_expr env left in
      let r = eval_expr env right in
      (match op with
       | Add -> Int64.add l r
       | Sub -> Int64.sub l r
       | Mul -> Int64.mul l r
       | Xor -> Int64.logxor l r
       | And -> Int64.logand l r
       | Or  -> Int64.logor l r
       | Shl -> Int64.shift_left l (Int64.to_int r)
       | Shr -> Int64.shift_right_logical l (Int64.to_int r))
  | IfZero (cond, then_e, else_e) ->
      let c = eval_expr env cond in
      if c = 0L then eval_expr env then_e
      else eval_expr env else_e

let eval_ref (f : pure_func) (args : (string * int64) list) : int64 =
  eval_expr args f.body

(* 2. Code Generation to Portable C / Native Backend *)
let rec codegen_expr (e : expr) : string =
  match e with
  | Const n -> Printf.sprintf "%LdLL" n
  | Var v -> v
  | BinOp (op, left, right) ->
      let l_str = codegen_expr left in
      let r_str = codegen_expr right in
      let op_str =
        match op with
        | Add -> "+"
        | Sub -> "-"
        | Mul -> "*"
        | Xor -> "^"
        | And -> "&"
        | Or  -> "|"
        | Shl -> "<<"
        | Shr -> ">>"
      in
      Printf.sprintf "((int64_t)(%s %s %s))" l_str op_str r_str
  | IfZero (cond, then_e, else_e) ->
      let c = codegen_expr cond in
      let t = codegen_expr then_e in
      let el = codegen_expr else_e in
      Printf.sprintf "((%s == 0LL) ? (%s) : (%s))" c t el

let emit_c_source (f : pure_func) : string =
  let param_decls =
    String.concat ", " (List.map (fun p -> Printf.sprintf "int64_t %s" p) f.params)
  in
  let body_c = codegen_expr f.body in
  let arg_parsers =
    List.mapi (fun i p ->
      Printf.sprintf "    int64_t %s = (int64_t)strtoll(argv[%d], NULL, 10);" p (i + 1)
    ) f.params |> String.concat "\n"
  in
  let arg_list = String.concat ", " f.params in
  let num_args = List.length f.params in
  Printf.sprintf {|/* Generated by INOS Native Backend (C007) */
#include <stdint.h>
#include <inttypes.h>
#include <stdio.h>
#include <stdlib.h>

static int64_t %s(%s) {
    return %s;
}

int main(int argc, char** argv) {
    if (argc < %d) {
        fprintf(stderr, "Usage: %%s <args...>\n", argv[0]);
        return 1;
    }
%s
    int64_t result = %s(%s);
    printf("%%" PRId64 "\n", result);
    return 0;
}
|} f.name param_decls body_c (num_args + 1) arg_parsers f.name arg_list

(* 3. Native Compilation via host toolchain *)
let compile_native (f : pure_func) ~(out_bin : string) : (unit, string) result =
  let c_src_path = out_bin ^ ".c" in
  let oc = open_out c_src_path in
  output_string oc (emit_c_source f);
  close_out oc;
  let cmd = Printf.sprintf "gcc -O2 -fwrapv -o '%s' '%s' 2>&1" out_bin c_src_path in
  let ic = Unix.open_process_in cmd in
  let buf = Buffer.create 128 in
  (try
     while true do
       Buffer.add_string buf (input_line ic);
       Buffer.add_char buf '\n'
     done
   with End_of_file -> ());
  let status = Unix.close_process_in ic in
  match status with
  | Unix.WEXITED 0 -> Ok ()
  | Unix.WEXITED n ->
      Error (Printf.sprintf "gcc failed with code %d:\n%s" n (Buffer.contents buf))
  | Unix.WSIGNALED s ->
      Error (Printf.sprintf "gcc killed by signal %d" s)
  | Unix.WSTOPPED s ->
      Error (Printf.sprintf "gcc stopped by signal %d" s)

(* 4. Native Execution *)
let run_native (bin_path : string) (args : int64 list) : (int64, string) result =
  let args_str = String.concat " " (List.map (fun a -> Printf.sprintf "%Ld" a) args) in
  let cmd = Printf.sprintf "'%s' %s 2>&1" bin_path args_str in
  let ic = Unix.open_process_in cmd in
  let line =
    try Some (input_line ic)
    with End_of_file -> None
  in
  let status = Unix.close_process_in ic in
  match status with
  | Unix.WEXITED 0 ->
      (match line with
       | Some s ->
           (try Ok (Int64.of_string (String.trim s))
            with _ -> Error (Printf.sprintf "Cannot parse integer output: '%s'" s))
       | None -> Error "No output from compiled binary")
  | Unix.WEXITED n ->
      Error (Printf.sprintf "Binary failed with exit code %d" n)
  | _ -> Error "Binary terminated abnormally"

(* 5. Verification: Vector equivalence between reference interpreter and native binary *)
let verify_vector (f : pure_func) (bin_path : string) (args : int64 list) : (bool * int64 * int64) =
  let env = List.combine f.params args in
  let ref_res = eval_ref f env in
  match run_native bin_path args with
  | Ok nat_res -> (ref_res = nat_res, ref_res, nat_res)
  | Error _ -> (false, ref_res, Int64.min_int)
