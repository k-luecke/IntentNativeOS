// tools/font_rasterizer/rasterize.c
// Offline build-time font rasterizer for INOS (Gate UI-03.1)
// Converts TTF/OTF fonts into zero-dependency Rust font tables for #[no_std] kernel.
// Features multiple font faces:
// 1. Title Face: Liberation Sans Bold @ 20px (modal headings, window titles, card headers)
// 2. UI Face: Liberation Sans Regular @ 16px (modal explanations, button labels, menus)
// 3. Serif Face: Liberation Serif Regular @ 16px (document editorial reading)

#include <stdio.h>
#include <stdlib.h>
#include <stdint.h>
#include <string.h>
#include <ft2build.h>
#include FT_FREETYPE_H

static const uint32_t UNICODE_EXTRA[] = {
    0x2014, // em-dash —
    0x201C, // left double quote “
    0x201D, // right double quote ”
    0x2022, // bullet •
    0x2192, // right arrow →
    0x2713, // checkmark ✓
};
#define NUM_EXTRA (sizeof(UNICODE_EXTRA) / sizeof(UNICODE_EXTRA[0]))

typedef struct {
    const char *name;
    const char *prefix;
    const char *font_file;
    int pixel_size;
} FontConfig;

static void emit_face(FILE *out, FT_Library ft, const FontConfig *cfg) {
    FT_Face face;
    if (FT_New_Face(ft, cfg->font_file, 0, &face)) {
        fprintf(stderr, "Error: FT_New_Face failed for %s\n", cfg->font_file);
        exit(1);
    }
    FT_Set_Pixel_Sizes(face, 0, cfg->pixel_size);

    int ascent = face->size->metrics.ascender >> 6;
    int descent = (-face->size->metrics.descender) >> 6;
    int line_height = face->size->metrics.height >> 6;
    if (line_height <= 0) line_height = ascent + descent + 2;

    fprintf(out, "// --- %s: %s @ %dpx ---\n", cfg->name, cfg->font_file, cfg->pixel_size);
    fprintf(out, "pub const %s_ASCENT: usize = %d;\n", cfg->prefix, ascent);
    fprintf(out, "pub const %s_DESCENT: usize = %d;\n", cfg->prefix, descent);
    fprintf(out, "pub const %s_LINE_HEIGHT: usize = %d;\n\n", cfg->prefix, line_height);

    int total_chars = (126 - 32 + 1) + NUM_EXTRA;
    uint32_t all_chars[256];
    int char_count = 0;

    for (uint32_t c = 32; c <= 126; c++) {
        all_chars[char_count++] = c;
    }
    for (size_t i = 0; i < NUM_EXTRA; i++) {
        all_chars[char_count++] = UNICODE_EXTRA[i];
    }

    // Emit byte buffers
    for (int idx = 0; idx < char_count; idx++) {
        uint32_t c = all_chars[idx];
        if (FT_Load_Char(face, c, FT_LOAD_RENDER)) {
            fprintf(stderr, "Warning: failed to load %s glyph U+%04X\n", cfg->prefix, c);
            continue;
        }
        FT_Bitmap *bmp = &face->glyph->bitmap;
        int sz = bmp->width * bmp->rows;

        fprintf(out, "static %s_GLYPH_%04X_DATA: [u8; %d] = [", cfg->prefix, c, sz > 0 ? sz : 1);
        if (sz == 0) {
            fprintf(out, "0");
        } else {
            for (int p = 0; p < sz; p++) {
                if (p % 16 == 0) fprintf(out, "\n    ");
                fprintf(out, "%u, ", bmp->buffer[p]);
            }
        }
        fprintf(out, "\n];\n\n");
    }

    // Emit table
    fprintf(out, "pub static %s_GLYPHS: [ProportionalGlyph; %d] = [\n", cfg->prefix, char_count);
    for (int idx = 0; idx < char_count; idx++) {
        uint32_t c = all_chars[idx];
        FT_Load_Char(face, c, FT_LOAD_RENDER);
        FT_Bitmap *bmp = &face->glyph->bitmap;
        int adv = face->glyph->advance.x >> 6;
        if (adv <= 0) adv = bmp->width + 1;

        fprintf(out, "    ProportionalGlyph {\n");
        fprintf(out, "        unicode: 0x%04X,\n", c);
        fprintf(out, "        width: %u,\n", bmp->width);
        fprintf(out, "        height: %u,\n", bmp->rows);
        fprintf(out, "        bearing_x: %d,\n", face->glyph->bitmap_left);
        fprintf(out, "        bearing_y: %d,\n", face->glyph->bitmap_top);
        fprintf(out, "        advance: %u,\n", adv);
        fprintf(out, "        data: &%s_GLYPH_%04X_DATA,\n", cfg->prefix, c);
        fprintf(out, "    },\n");
    }
    fprintf(out, "];\n\n");

    FT_Done_Face(face);
}

int main(int argc, char **argv) {
    const char *out_path = "kernel/src/graphics/proportional_font.rs";
    if (argc > 1) out_path = argv[1];

    FT_Library ft;
    if (FT_Init_FreeType(&ft)) {
        fprintf(stderr, "Error: FT_Init_FreeType failed\n");
        return 1;
    }

    FILE *out = fopen(out_path, "w");
    if (!out) {
        fprintf(stderr, "Error: Cannot open %s for writing\n", out_path);
        return 1;
    }

    fprintf(out, "// kernel/src/graphics/proportional_font.rs\n");
    fprintf(out, "// Auto-generated by tools/font_rasterizer/rasterize.c for INOS Gate UI-03.1.\n");
    fprintf(out, "// Source Fonts: Liberation Sans & Liberation Serif (SIL Open Font License v1.1)\n");
    fprintf(out, "// Digitized data copyright (c) 2010 Google Corporation with Reserved Font Arimo, Tinos and Cousine.\n");
    fprintf(out, "// Copyright (c) 2012 Red Hat, Inc. with Reserved Font Name Liberation.\n\n");
    fprintf(out, "#![no_std]\n\n");

    fprintf(out, "/// Typographic font faces supported natively in INOS\n");
    fprintf(out, "#[derive(Clone, Copy, PartialEq, Eq, Debug)]\n");
    fprintf(out, "pub enum FontFace {\n");
    fprintf(out, "    Title, // 20px Liberation Sans Bold (headings, modal titles, card headers)\n");
    fprintf(out, "    Ui,    // 16px Liberation Sans Regular (modal explanations, button labels, launcher)\n");
    fprintf(out, "    Serif, // 16px Liberation Serif Regular (document editorial reading)\n");
    fprintf(out, "}\n\n");

    fprintf(out, "/// Represents a single proportional anti-aliased glyph with grayscale coverage mask\n");
    fprintf(out, "#[derive(Clone, Copy)]\n");
    fprintf(out, "pub struct ProportionalGlyph {\n");
    fprintf(out, "    pub unicode: u32,\n");
    fprintf(out, "    pub width: u8,\n");
    fprintf(out, "    pub height: u8,\n");
    fprintf(out, "    pub bearing_x: i8,\n");
    fprintf(out, "    pub bearing_y: i8,\n");
    fprintf(out, "    pub advance: u8,\n");
    fprintf(out, "    pub data: &'static [u8],\n");
    fprintf(out, "}\n\n");

    FontConfig configs[] = {
        {"Title (Sans Bold)", "TITLE", "/usr/share/fonts/truetype/liberation/LiberationSans-Bold.ttf", 20},
        {"UI (Sans Regular)", "UI", "/usr/share/fonts/truetype/liberation/LiberationSans-Regular.ttf", 16},
        {"Serif (Serif Regular)", "SERIF", "/usr/share/fonts/truetype/liberation/LiberationSerif-Regular.ttf", 16},
    };
    int num_configs = sizeof(configs) / sizeof(configs[0]);

    for (int i = 0; i < num_configs; i++) {
        emit_face(out, ft, &configs[i]);
    }

    // Lookup function
    fprintf(out, "/// Fast O(1) ASCII lookup for proportional glyphs\n");
    fprintf(out, "pub fn lookup_proportional_glyph(face: FontFace, ch: char) -> Option<&'static ProportionalGlyph> {\n");
    fprintf(out, "    let code = ch as u32;\n");
    fprintf(out, "    let table: &'static [ProportionalGlyph] = match face {\n");
    fprintf(out, "        FontFace::Title => &TITLE_GLYPHS,\n");
    fprintf(out, "        FontFace::Ui => &UI_GLYPHS,\n");
    fprintf(out, "        FontFace::Serif => &SERIF_GLYPHS,\n");
    fprintf(out, "    };\n");
    fprintf(out, "    if code >= 32 && code <= 126 {\n");
    fprintf(out, "        return Some(&table[(code - 32) as usize]);\n");
    fprintf(out, "    }\n");
    fprintf(out, "    for g in &table[95..] {\n");
    fprintf(out, "        if g.unicode == code {\n");
    fprintf(out, "            return Some(g);\n");
    fprintf(out, "        }\n");
    fprintf(out, "    }\n");
    fprintf(out, "    None\n");
    fprintf(out, "}\n\n");

    // Metric accessors
    fprintf(out, "pub fn font_line_height(face: FontFace) -> usize {\n");
    fprintf(out, "    match face {\n");
    fprintf(out, "        FontFace::Title => TITLE_LINE_HEIGHT,\n");
    fprintf(out, "        FontFace::Ui => UI_LINE_HEIGHT,\n");
    fprintf(out, "        FontFace::Serif => SERIF_LINE_HEIGHT,\n");
    fprintf(out, "    }\n");
    fprintf(out, "}\n\n");

    fprintf(out, "pub fn font_ascent(face: FontFace) -> usize {\n");
    fprintf(out, "    match face {\n");
    fprintf(out, "        FontFace::Title => TITLE_ASCENT,\n");
    fprintf(out, "        FontFace::Ui => UI_ASCENT,\n");
    fprintf(out, "        FontFace::Serif => SERIF_ASCENT,\n");
    fprintf(out, "    }\n");
    fprintf(out, "}\n\n");

    fprintf(out, "pub fn font_descent(face: FontFace) -> usize {\n");
    fprintf(out, "    match face {\n");
    fprintf(out, "        FontFace::Title => TITLE_DESCENT,\n");
    fprintf(out, "        FontFace::Ui => UI_DESCENT,\n");
    fprintf(out, "        FontFace::Serif => SERIF_DESCENT,\n");
    fprintf(out, "    }\n");
    fprintf(out, "}\n\n");

    fprintf(out, "// Legacy compatibility aliases\n");
    fprintf(out, "pub const FONT_ASCENT: usize = SERIF_ASCENT;\n");
    fprintf(out, "pub const FONT_DESCENT: usize = SERIF_DESCENT;\n");
    fprintf(out, "pub const FONT_LINE_HEIGHT: usize = SERIF_LINE_HEIGHT;\n");

    fclose(out);
    FT_Done_FreeType(ft);

    printf("Successfully generated font tables to %s\n", out_path);
    return 0;
}
